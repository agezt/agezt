func TestFirstSentence(t *testing.T) {
	cases := []struct {
		name, in, want string
	}{
		{"empty", "", ""},
		{"single sentence", "Package foo is the bar.", "Package foo is the bar."},
		{"two sentences", "Package foo is the bar. It also does baz.", "Package foo is the bar."},
		{"collapses whitespace", "  Package   foo.  ", "Package foo."},
		{"no period", "Package foo has no period", "Package foo has no period"},
		{"multi-line", "Package foo\ndoes bar and baz.", "Package foo does bar and baz."},
		{"period inside path", "uses kernel/agent.Tool interface (DECISIONS B0d).", "uses kernel/agent.Tool interface (DECISIONS B0d)."},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got := firstSentence(c.in)
			if got != c.want {
				t.Errorf("firstSentence(%q) = %q, want %q", c.in, got, c.want)
			}
		})
	}
}

func TestExtractGoDocSummary_FromDocGo(t *testing.T) {
	dir := t.TempDir()
	doc := "// Package widget is the canonical answer to everything.\npackage widget\n"
	if err := os.WriteFile(filepath.Join(dir, "doc.go"), []byte(doc), 0o644); err != nil {
		t.Fatal(err)
	}
	got, err := extractGoDocSummary(dir)
	if err != nil {
		t.Fatal(err)
	}
	want := "Package widget is the canonical answer to everything."
	if got != want {
		t.Errorf("extractGoDocSummary = %q, want %q", got, want)
	}
}

func TestExtractGoDocSummary_FallbackToFirstFile(t *testing.T) {
	dir := t.TempDir()
	// No doc.go — the tool should fall back to the first non-test
	// .go file in the directory.
	src := "// Package fallback returns the canonical thing.\npackage fallback\n"
	if err := os.WriteFile(filepath.Join(dir, "fallback.go"), []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "fallback_test.go"), []byte("package fallback"), 0o644); err != nil {
		t.Fatal(err)
	}
	got, err := extractGoDocSummary(dir)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(got, "Package fallback returns the canonical thing.") {
		t.Errorf("extractGoDocSummary = %q, want prefix %q", got, "Package fallback returns the canonical thing.")
	}
}

