func TestRun_GeneratesAndIsIdempotent(t *testing.T) {
	root := t.TempDir()
	// Lay out a tiny repo: one kernel package with doc.go.
	must := func(err error) { t.Helper(); if err != nil { t.Fatal(err) } }
	must(os.MkdirAll(filepath.Join(root, "kernel", "alpha"), 0o755))
	must(os.WriteFile(
		filepath.Join(root, "kernel", "alpha", "doc.go"),
		[]byte("// Package alpha is the test package.\npackage alpha\n"),
		0o644,
	))
	must(os.WriteFile(
		filepath.Join(root, "kernel", "alpha", "alpha.go"),
		[]byte("package alpha\n"),
		0o644,
	))

	out := filepath.Join(root, "out")
	if err := run(root, out, false); err != nil {
		t.Fatal(err)
	}
	data, err := os.ReadFile(filepath.Join(out, "STRUCTURE.kernel.md"))
	if err != nil {
		t.Fatalf("read generated file: %v", err)
	}
	got := string(data)
	if !strings.Contains(got, "`kernel/alpha`") {
		t.Errorf("expected kernel/alpha in output, got:\n%s", got)
	}
	if !strings.Contains(got, "Package alpha is the test package.") {
		t.Errorf("expected first sentence in output, got:\n%s", got)
	}
	// Re-run is idempotent: no error, no extra output, content
	// unchanged.
	if err := run(root, out, false); err != nil {
		t.Fatal(err)
	}
	data2, _ := os.ReadFile(filepath.Join(out, "STRUCTURE.kernel.md"))
	if string(data) != string(data2) {
		t.Errorf("second run produced different output")
	}
}
