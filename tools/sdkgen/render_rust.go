package main

// The Rust SDK's catalog.
//
// The Rust SDK is the one SDK whose runtime has no dependency at all: standard
// library only, with its own HTTP/1.1 client and its own JSON codec. So the
// generated Rust cannot lean on serde — it leans on the crate's own
// `json::Value`.
//
// Two rules shape the rendering:
//
//  1. **The wire names live here, not in the client.** Every row gets a
//     `from_value` that reads the wire names and a `to_value` that writes them,
//     so `client.rs` never spells a field name of its own.
//
//  2. **The types are flat.** A missing field reads as its zero value (an
//     empty string, zero, false, an empty list) rather than an `Option`. The
//     Rust SDK's public API has always been flat — `Health.version` is a
//     `String`, not an `Option<String>` — and the contract's rows say the same
//     thing about the daemon's answers: a row names the fields every answer
//     carries, and the daemon may add fields the SDK ignores.
//
// The rendering is deliberately written in the shape `rustfmt` produces: the
// repository's `cargo fmt --check` gate covers this file like every other file
// in the crate, so the generator must not depend on a formatter being run
// afterwards.

import (
	"bytes"
	"fmt"
	"strings"

	"github.com/agezt/agezt/kernel/contract/restapiapi"
)

// rustPreamble is the generated Rust file's header.
const rustPreamble = `//! Generated by 'go run ./tools/sdkgen' from kernel/contract/restapiapi.
//!
//! DO NOT EDIT: regenerate with 'go run ./tools/sdkgen'.
//!
//! The daemon's /api/v1 contract as Rust: the paths the SDK calls and the
//! wire rows the daemon answers with. The client in client.rs uses these
//! names, so a path or a field exists in exactly one place.

use std::collections::BTreeMap;

use crate::json::Value;
`

// rustFnCallWidth is rustfmt's `fn_call_width`: the widest a call's arguments
// may be while the call still stays on one line. The default is 60 — narrower
// than `max_width`, which is why a long argument list breaks into one
// argument per line even when the whole call would fit.
const rustFnCallWidth = 60

// rustKeywords are the words Rust reserves. A field whose local name is one
// of them is escaped with `r#` — unless the contract declares a local name
// for that language, which is the cleaner answer (the api_error row's `type`
// is `kind` in Rust).
var rustKeywords = map[string]bool{
	"as": true, "async": true, "await": true, "become": true, "box": true,
	"break": true, "const": true, "continue": true, "crate": true, "do": true,
	"dyn": true, "else": true, "enum": true, "extern": true, "false": true,
	"final": true, "fn": true, "for": true, "if": true, "impl": true,
	"in": true, "let": true, "loop": true, "macro": true, "match": true,
	"mod": true, "move": true, "mut": true, "override": true, "priv": true,
	"pub": true, "ref": true, "return": true, "self": true, "static": true,
	"struct": true, "super": true, "trait": true, "true": true, "try": true,
	"type": true, "typeof": true, "unsafe": true, "unsized": true, "use": true,
	"virtual": true, "where": true, "while": true, "yield": true,
}

// renderRust renders the Rust SDK's catalog: the paths and the wire rows.
func renderRust(cat catalog) []byte {
	var b bytes.Buffer
	b.WriteString(rustPreamble)

	// --- the paths --------------------------------------------------------
	b.WriteString("\n/// The daemon's REST paths.\n")
	b.WriteString("pub mod paths {\n")
	for _, p := range cat.Paths {
		fmt.Fprintf(&b, "    /// %s\n", p.Doc)
		fmt.Fprintf(&b, "    pub const %s: &str = %q;\n", upperSnake(p.Name), p.Path)
	}
	b.WriteString("\n    /// Every path of the SDK contract.\n")
	fmt.Fprintf(&b, "    pub const ALL: [&str; %d] = [\n", len(cat.Paths))
	for _, p := range cat.Paths {
		fmt.Fprintf(&b, "        %s,\n", upperSnake(p.Name))
	}
	b.WriteString("    ];\n")
	b.WriteString("}\n")

	// --- the rows ---------------------------------------------------------
	for _, r := range cat.Rows {
		rustRow(&b, r)
	}
	rustHelpers(&b, cat)
	return b.Bytes()
}

// rustRow renders one wire row: the struct, the reader and the writer.
func rustRow(b *bytes.Buffer, r restapiapi.Row) {
	name := pascal(r.Name)
	fmt.Fprintf(b, "\n/// %s\n", r.Doc)
	b.WriteString("#[derive(Debug, Clone, Default)]\n")
	fmt.Fprintf(b, "pub struct %s {\n", name)
	for _, f := range r.Fields {
		fmt.Fprintf(b, "    /// %s\n", f.Doc)
		fmt.Fprintf(b, "    pub %s: %s,\n", rustFieldName(f), rustType(f.Type))
	}
	b.WriteString("}\n")

	fmt.Fprintf(b, "\nimpl %s {\n", name)
	b.WriteString("    /// Read the row from the daemon's JSON.\n")
	b.WriteString("    pub fn from_value(v: &Value) -> Self {\n")
	b.WriteString("        Self {\n")
	for _, f := range r.Fields {
		fmt.Fprintf(b, "            %s: %s,\n", rustFieldName(f), rustRead(f))
	}
	b.WriteString("        }\n")
	b.WriteString("    }\n")
	b.WriteString("\n")
	b.WriteString("    /// Write the row as the daemon's request body.\n")
	b.WriteString("    pub fn to_value(&self) -> Value {\n")
	b.WriteString("        let mut m = BTreeMap::new();\n")
	for _, f := range r.Fields {
		b.WriteString(rustWrite(f))
	}
	b.WriteString("        Value::Object(m)\n")
	b.WriteString("    }\n")
	b.WriteString("}\n")
}

// rustType maps a wire type onto its Rust spelling.
func rustType(t restapiapi.Type) string {
	switch t {
	case restapiapi.TypeString:
		return "String"
	case restapiapi.TypeInt:
		return "i64"
	case restapiapi.TypeBool:
		return "bool"
	case restapiapi.TypeStringSlice:
		return "Vec<String>"
	case restapiapi.TypeAnySlice:
		return "Vec<Value>"
	case restapiapi.TypeAnyObject:
		return "BTreeMap<String, Value>"
	case restapiapi.TypeIntMap:
		return "BTreeMap<String, i64>"
	case restapiapi.TypeMail:
		return "Mail"
	case restapiapi.TypeMailSlice:
		return "Vec<Mail>"
	default:
		return "Value"
	}
}

// rustFieldName is a field's Rust name: the contract's local name for Rust,
// in snake_case, escaped when it is a reserved word.
func rustFieldName(f restapiapi.Field) string {
	name := rustSnake(f.LocalName("rust"))
	if rustKeywords[name] {
		return "r#" + name
	}
	return name
}

// rustSnake turns a wire name into a Rust identifier ("replyTo" -> "reply_to").
func rustSnake(name string) string {
	var b strings.Builder
	for i, r := range name {
		switch {
		case r >= 'A' && r <= 'Z':
			if i > 0 {
				b.WriteByte('_')
			}
			b.WriteRune(r + 32)
		case (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9'):
			b.WriteRune(r)
		default:
			b.WriteByte('_')
		}
	}
	return b.String()
}

// rustRead renders the read of one field inside from_value.
func rustRead(f restapiapi.Field) string {
	switch f.Type {
	case restapiapi.TypeString:
		return fmt.Sprintf("v.str(%q).unwrap_or(\"\").to_string()", f.Name)
	case restapiapi.TypeInt:
		return fmt.Sprintf("v.get(%q).and_then(Value::as_i64).unwrap_or(0)", f.Name)
	case restapiapi.TypeBool:
		return fmt.Sprintf("v.get(%q).and_then(Value::as_bool).unwrap_or(false)", f.Name)
	case restapiapi.TypeStringSlice:
		return fmt.Sprintf("strings(v.get(%q))", f.Name)
	case restapiapi.TypeAnySlice:
		return fmt.Sprintf("values(v.get(%q))", f.Name)
	case restapiapi.TypeAnyObject:
		return fmt.Sprintf("object(v.get(%q))", f.Name)
	case restapiapi.TypeIntMap:
		return fmt.Sprintf("int_map(v.get(%q))", f.Name)
	case restapiapi.TypeMail:
		return fmt.Sprintf("mail(v.get(%q))", f.Name)
	case restapiapi.TypeMailSlice:
		return fmt.Sprintf("mails(v.get(%q))", f.Name)
	default:
		return fmt.Sprintf("v.get(%q).cloned().unwrap_or(Value::Null)", f.Name)
	}
}

// rustWrite renders the write of one field inside to_value.
//
// A required field is always written; an optional one is written only when it
// holds something — an empty string, a zero, a false, an empty list. That is
// what the daemon expects: an absent optional field and an empty one are not
// the same request.
func rustWrite(f restapiapi.Field) string {
	local := rustFieldName(f)
	key := fmt.Sprintf("%q", f.Name)
	var expr, cond string
	switch f.Type {
	case restapiapi.TypeString:
		expr = fmt.Sprintf("Value::Str(self.%s.clone())", local)
		cond = fmt.Sprintf("!self.%s.is_empty()", local)
	case restapiapi.TypeInt:
		expr = fmt.Sprintf("Value::Int(self.%s)", local)
		cond = fmt.Sprintf("self.%s != 0", local)
	case restapiapi.TypeBool:
		expr = fmt.Sprintf("Value::Bool(self.%s)", local)
		cond = fmt.Sprintf("self.%s", local)
	case restapiapi.TypeStringSlice:
		expr = fmt.Sprintf("strings_value(&self.%s)", local)
		cond = fmt.Sprintf("!self.%s.is_empty()", local)
	case restapiapi.TypeAnySlice:
		expr = fmt.Sprintf("Value::Array(self.%s.clone())", local)
		cond = fmt.Sprintf("!self.%s.is_empty()", local)
	case restapiapi.TypeAnyObject:
		expr = fmt.Sprintf("Value::Object(self.%s.clone())", local)
		cond = fmt.Sprintf("!self.%s.is_empty()", local)
	case restapiapi.TypeIntMap:
		expr = fmt.Sprintf("int_map_value(&self.%s)", local)
		cond = fmt.Sprintf("!self.%s.is_empty()", local)
	case restapiapi.TypeMail:
		expr = fmt.Sprintf("self.%s.to_value()", local)
	case restapiapi.TypeMailSlice:
		expr = fmt.Sprintf("mails_value(&self.%s)", local)
	default:
		return ""
	}
	if f.Required {
		return rustInsert(8, key, expr)
	}
	return fmt.Sprintf("        if %s {\n%s        }\n", cond, rustInsert(12, key, expr))
}

// rustInsert renders one `m.insert(...)` call.
//
// rustfmt keeps a call on one line only when its ARGUMENTS fit within
// `fn_call_width` (60 by default) — not when the whole line fits within
// `max_width` (100). The repository's `cargo fmt --check` gate covers this
// generated file like every other file in the crate, so the generator has to
// produce the shape rustfmt would produce, not merely a shape it tolerates.
func rustInsert(indent int, key, expr string) string {
	pad := strings.Repeat(" ", indent)
	args := key + ".to_string(), " + expr
	if len(args) <= rustFnCallWidth {
		return fmt.Sprintf("%sm.insert(%s);\n", pad, args)
	}
	return fmt.Sprintf("%sm.insert(\n%s    %s.to_string(),\n%s    %s,\n%s);\n",
		pad, pad, key, pad, expr, pad)
}

// rustHelpers writes the small readers the rows need. Only the ones the
// generated rows actually use are written, so the file carries no dead code.
func rustHelpers(b *bytes.Buffer, cat catalog) {
	need := map[string]bool{}
	for _, r := range cat.Rows {
		for _, f := range r.Fields {
			switch f.Type {
			case restapiapi.TypeStringSlice:
				need["strings"] = true
				need["strings_value"] = true
			case restapiapi.TypeAnySlice:
				need["values"] = true
			case restapiapi.TypeAnyObject:
				need["object"] = true
			case restapiapi.TypeIntMap:
				need["int_map"] = true
				need["int_map_value"] = true
			case restapiapi.TypeMail:
				need["mail"] = true
			case restapiapi.TypeMailSlice:
				need["mails"] = true
				need["mails_value"] = true
			}
		}
	}
	if need["strings"] {
		b.WriteString("\n/// Read a JSON array of strings.\n")
		b.WriteString("fn strings(v: Option<&Value>) -> Vec<String> {\n")
		b.WriteString("    let mut out = Vec::new();\n")
		b.WriteString("    if let Some(a) = v.and_then(Value::as_array) {\n")
		b.WriteString("        for e in a {\n")
		b.WriteString("            if let Some(s) = e.as_str() {\n")
		b.WriteString("                out.push(s.to_string());\n")
		b.WriteString("            }\n")
		b.WriteString("        }\n")
		b.WriteString("    }\n")
		b.WriteString("    out\n")
		b.WriteString("}\n")
	}
	if need["strings_value"] {
		b.WriteString("\n/// Write a JSON array of strings.\n")
		b.WriteString("fn strings_value(items: &[String]) -> Value {\n")
		b.WriteString("    let mut out = Vec::new();\n")
		b.WriteString("    for s in items {\n")
		b.WriteString("        out.push(Value::Str(s.clone()));\n")
		b.WriteString("    }\n")
		b.WriteString("    Value::Array(out)\n")
		b.WriteString("}\n")
	}
	if need["values"] {
		b.WriteString("\n/// Read a JSON array of free-form values.\n")
		b.WriteString("fn values(v: Option<&Value>) -> Vec<Value> {\n")
		b.WriteString("    match v.and_then(Value::as_array) {\n")
		b.WriteString("        Some(a) => a.to_vec(),\n")
		b.WriteString("        None => Vec::new(),\n")
		b.WriteString("    }\n")
		b.WriteString("}\n")
	}
	if need["object"] {
		b.WriteString("\n/// Read a JSON object.\n")
		b.WriteString("fn object(v: Option<&Value>) -> BTreeMap<String, Value> {\n")
		b.WriteString("    match v {\n")
		b.WriteString("        Some(Value::Object(m)) => m.clone(),\n")
		b.WriteString("        _ => BTreeMap::new(),\n")
		b.WriteString("    }\n")
		b.WriteString("}\n")
	}
	if need["int_map"] {
		b.WriteString("\n/// Read a JSON object whose values are integers.\n")
		b.WriteString("fn int_map(v: Option<&Value>) -> BTreeMap<String, i64> {\n")
		b.WriteString("    let mut out = BTreeMap::new();\n")
		b.WriteString("    if let Some(Value::Object(m)) = v {\n")
		b.WriteString("        for (k, val) in m {\n")
		b.WriteString("            out.insert(k.clone(), val.as_i64().unwrap_or(0));\n")
		b.WriteString("        }\n")
		b.WriteString("    }\n")
		b.WriteString("    out\n")
		b.WriteString("}\n")
	}
	if need["int_map_value"] {
		b.WriteString("\n/// Write a JSON object whose values are integers.\n")
		b.WriteString("fn int_map_value(items: &BTreeMap<String, i64>) -> Value {\n")
		b.WriteString("    let mut m = BTreeMap::new();\n")
		b.WriteString("    for (k, v) in items {\n")
		b.WriteString("        m.insert(k.clone(), Value::Int(*v));\n")
		b.WriteString("    }\n")
		b.WriteString("    Value::Object(m)\n")
		b.WriteString("}\n")
	}
	if need["mail"] {
		b.WriteString("\n/// Read one message.\n")
		b.WriteString("fn mail(v: Option<&Value>) -> Mail {\n")
		b.WriteString("    Mail::from_value(v.unwrap_or(&Value::Null))\n")
		b.WriteString("}\n")
	}
	if need["mails"] {
		b.WriteString("\n/// Read a list of messages.\n")
		b.WriteString("fn mails(v: Option<&Value>) -> Vec<Mail> {\n")
		b.WriteString("    let mut out = Vec::new();\n")
		b.WriteString("    if let Some(a) = v.and_then(Value::as_array) {\n")
		b.WriteString("        for e in a {\n")
		b.WriteString("            out.push(Mail::from_value(e));\n")
		b.WriteString("        }\n")
		b.WriteString("    }\n")
		b.WriteString("    out\n")
		b.WriteString("}\n")
	}
	if need["mails_value"] {
		b.WriteString("\n/// Write a list of messages.\n")
		b.WriteString("fn mails_value(items: &[Mail]) -> Value {\n")
		b.WriteString("    let mut out = Vec::new();\n")
		b.WriteString("    for m in items {\n")
		b.WriteString("        out.push(m.to_value());\n")
		b.WriteString("    }\n")
		b.WriteString("    Value::Array(out)\n")
		b.WriteString("}\n")
	}
}
